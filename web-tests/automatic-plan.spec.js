const { test, expect } = require('@playwright/test');

test('new plan books are scheduled on save and replacement stays atomic', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-25T12:00:00'));
  await page.setViewportSize({ width: 360, height: 740 });
  await page.goto('./');
  const main = page.getByRole('navigation', { name: 'Main navigation' });
  await main.getByRole('button', { name: 'Plan' }).click();
  const open = page.getByRole('button', { name: 'New plan', exact: true });
  const dialog = page.getByRole('dialog', { name: 'New plan' });
  await open.click();
  await dialog.getByLabel('Finish date').fill('2026-12-31');
  await dialog.getByRole('button', { name: 'Add a book' }).click();
  await dialog.getByLabel('Book name').fill('Paper');
  await dialog.getByLabel('End page').fill('120');
  await dialog.getByRole('button', { name: 'Add a book' }).click();
  const audio = dialog.getByRole('group', { name: 'New book' }).last();
  await audio.getByLabel('Book type').selectOption('Audiobooks');
  await audio.getByLabel('Book name').fill('Audio');
  await audio.getByLabel('End time').fill('2:30');
  await dialog.getByRole('button', { name: 'Create plan' }).click();
  await expect(dialog).toBeHidden();
  await expect(page.locator('#new-plan-status')).toBeEmpty();
  await page.waitForFunction(() => typeof bundleWritePending === 'undefined' || !bundleWritePending);
  const bundle = () => page.evaluate(() => readBundleFiles());
  const saved = await bundle();
  expect(saved.books.sections[0].books[0].baseline_schedule.deadline).toBe('2026-12-31');
  expect(saved.books.sections[2].books[0].end_time_seconds).toBe(9000);
  page.once('dialog', (prompt) => prompt.dismiss());
  await open.click();
  await expect(dialog).toBeHidden();
  page.once('dialog', (prompt) => prompt.accept());
  await open.click();
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  expect(await bundle()).toEqual(saved);
  await page.getByRole('button', { name: 'Reading schedule', exact: true }).click();
  await expect(page.locator('#plan-schedule input, #plan-schedule button')).toHaveCount(0);
  await main.getByRole('button', { name: 'Books' }).click();
  const books = page.locator('#book-form');
  await books.getByLabel('Title', { exact: true }).fill('New paper');
  await books.getByLabel('End page', { exact: true }).fill('120');
  await books.getByRole('button', { name: 'Add', exact: true }).click();
  await expect(page.getByTestId('editor-status')).toBeEmpty();
  await page.waitForFunction(() => typeof bundleWritePending === 'undefined' || !bundleWritePending);
  const updated = await bundle();
  expect(updated.books.sections[0].books).toHaveLength(2);
  expect(updated.books.sections[0].books[0].baseline_schedule.deadline).not.toBe('2026-12-31');
  expect(updated.books.sections[0].books[1].baseline_schedule.deadline).toBe('2026-12-31');
  await main.getByRole('button', { name: 'Charts' }).click();
  await expect(page.getByRole('img', { name: 'Reading chart for Paper', exact: true })).toBeVisible({ timeout: 2000 });
  const chartBook = page.getByRole('combobox', { name: 'Book' });
  await chartBook.click();
  await expect(page.getByRole('option', { name: /Audio$/ })).toBeVisible();
  await expect(page.getByRole('option', { name: /New paper$/ })).toHaveCount(0);
  await page.getByRole('option', { name: /Audio$/ }).click();
  await page.getByRole('button', { name: 'All', exact: true }).click();
  await chartBook.click();
  await page.getByRole('option', { name: /New paper$/ }).click();
  const futureChart = page.getByRole('img', { name: 'Reading chart for New paper' });
  await expect(futureChart.locator('.chart-date-label').first()).toHaveText(
    updated.books.sections[0].books[1].baseline_schedule.start_date.slice(5));
  await expect(futureChart.getByText('Today', { exact: true })).toHaveCount(0);
  await main.getByRole('button', { name: 'Plan' }).click();
  page.once('dialog', (prompt) => prompt.accept());
  await open.click();
  await dialog.getByRole('button', { name: 'Create plan' }).click();
  await expect(dialog).toBeHidden();
  expect((await bundle()).books.sections.flatMap((section) => section.books)).toEqual([]);
  expect((await bundle()).sessions.sessions).toEqual({});
});
